"""Generate serialized TypeScript event types from backend Pydantic JSON Schema."""

import argparse
import json
from pathlib import Path

from app.events import EVENT_ADAPTER

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / "frontend" / "src" / "events.ts"


def ts_type(schema):
    if "$ref" in schema:
        return schema["$ref"].rsplit("/", 1)[-1]
    if "const" in schema:
        return json.dumps(schema["const"])
    if "enum" in schema:
        return " | ".join(json.dumps(value) for value in schema["enum"])
    for union in ("anyOf", "oneOf"):
        if union in schema:
            return " | ".join(ts_type(value) for value in schema[union])
    kind = schema.get("type")
    if kind == "array":
        return f"Array<{ts_type(schema['items'])}>"
    if kind == "object":
        # model_dump_json includes defaults: every serialized property is present.
        return (
            "{\n"
            + "\n".join(
                f"  {key}: {ts_type(value)};" for key, value in schema["properties"].items()
            )
            + "\n}"
        )
    if kind in ("string", "boolean", "null"):
        return kind
    if kind in ("integer", "number"):
        return "number"
    raise ValueError(f"Unsupported event schema: {schema}")


def generated_types():
    schema = EVENT_ADAPTER.json_schema(mode="serialization")
    definitions = "\n\n".join(
        f"export type {name} = {ts_type(value)};" for name, value in schema["$defs"].items()
    )
    return (
        "// Generated by scripts/generate_event_types.py; edit backend events.py instead.\n\n"
        + definitions
        + f"\n\nexport type Event = {ts_type(schema)};\n"
    )


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    output = generated_types()
    if args.check:
        if not TARGET.exists() or TARGET.read_text() != output:
            raise SystemExit(
                "Event types are stale. Run: uv run python scripts/generate_event_types.py"
            )
        print("Backend and frontend event types match.")
    else:
        TARGET.write_text(output)
        print(f"Generated {TARGET.relative_to(ROOT)}")
